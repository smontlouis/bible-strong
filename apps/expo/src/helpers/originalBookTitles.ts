export type OriginalBookTitle = { title: string; lang: 'he' | 'grc' | 'la'; dir: 'rtl' | 'ltr' }

const LAST_OLD_TESTAMENT_BOOK = 39

/**
 * The book's title in the version's own language, for a Hebrew, Greek or Latin version; none for
 * a French or English one, whose frame already speaks its language. BHG reads the Old
 * Testament in Hebrew and the New in Greek.
 */
export const getOriginalBookTitle = (
  bookNumber: number,
  versionId?: string
): OriginalBookTitle | null => {
  const language = versionId ? versions[versionId]?.language : undefined
  const titleLanguage =
    language === 'he-grc' ? (bookNumber <= LAST_OLD_TESTAMENT_BOOK ? 'he' : 'grc') : language

  if (titleLanguage === 'he') {
    const title = HEBREW[bookNumber]
    return title ? { title, lang: 'he', dir: 'rtl' } : null
  }
  if (titleLanguage === 'grc') {
    const title = GREEK[bookNumber]
    return title ? { title, lang: 'grc', dir: 'ltr' } : null
  }
  if (titleLanguage === 'la') {
    const title = LATIN[bookNumber]
    return title ? { title, lang: 'la', dir: 'ltr' } : null
  }
  return null
}
