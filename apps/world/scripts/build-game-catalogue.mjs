import { readdir, readFile, writeFile } from 'node:fs/promises'
import { createHash } from 'node:crypto'

const root = new URL('../', import.meta.url)
const imports = [],
  questions = [],
  identities = [],
  hash = createHash('sha256')
const ids = new Set()
for (const [directory, target, type] of [
  ['question-bank', questions, 'CatalogueQuestion'],
  ['who-bank', identities, 'CatalogueIdentity'],
]) {
  for (const name of (await readdir(new URL(directory, root)))
    .filter(n => n.endsWith('.json'))
    .sort()) {
    const content = await readFile(new URL(`${directory}/${name}`, root), 'utf8')
    hash.update(directory + '/' + name + '\n' + content)
    const rows = JSON.parse(content)
    for (const row of rows) {
      if (ids.has(row.id)) throw new Error(`Duplicate catalogue ID: ${row.id}`)
      ids.add(row.id)
    }
    const variable = `part${imports.length}`
    imports.push(`import ${variable} from '../../${directory}/${name}'`)
    target.push(`...(${variable} as ${type}[])`)
  }
}
const output = `// Generated by scripts/build-game-catalogue.mjs. Server-only seed, never a client import.
import type { CatalogueQuestion, CatalogueIdentity } from '../../src/game-catalogue'
${imports.join('\n')}
export const catalogueRevision = '${hash.digest('hex')}'
export const questionSeed: CatalogueQuestion[] = [${questions.join(', ')}]
export const identitySeed: CatalogueIdentity[] = [${identities.join(', ')}]
`
const destination = new URL('server/games/catalogue-seed.generated.ts', root)
if ((await readFile(destination, 'utf8').catch(() => '')) !== output)
  await writeFile(destination, output)
console.log(`Game catalogue manifest: ${ids.size} bilingual records`)
