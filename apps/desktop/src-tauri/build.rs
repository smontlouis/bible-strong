//! Compiles the Offline-copy archive keys into the binary (ADR-0065, ADR-0107).
//!
//! `BIBLE_STRONG_ARCHIVE_KEYS` holds `<version>:<base64 32-byte key>` pairs, as for the mobile
//! config plugin. Each key is XOR-masked with random bytes so it never appears whole in the
//! binary; that only keeps it out of string searches, it is not encryption. Without keys the
//! build still works and the app reports every key version as unavailable.

use base64::Engine;
use std::{collections::BTreeSet, env, fs, path::PathBuf};

const ARCHIVE_KEYS_ENV: &str = "BIBLE_STRONG_ARCHIVE_KEYS";

fn parse_archive_keys(value: &str) -> Vec<(u32, Vec<u8>)> {
    let mut versions = BTreeSet::new();
    value
        .split(',')
        .map(str::trim)
        .filter(|pair| !pair.is_empty())
        .map(|pair| {
            let (version, key) = pair.split_once(':').unwrap_or_else(|| {
                panic!("{ARCHIVE_KEYS_ENV} entries must look like <version>:<base64 key>")
            });
            let version: u32 = version
                .trim()
                .parse()
                .ok()
                .filter(|version| *version > 0)
                .unwrap_or_else(|| panic!("{ARCHIVE_KEYS_ENV} versions must be positive integers"));
            let key = base64::engine::general_purpose::STANDARD
                .decode(key.trim())
                .unwrap_or_else(|_| panic!("{ARCHIVE_KEYS_ENV} key {version} is not base64"));
            assert!(
                key.len() == 32,
                "{ARCHIVE_KEYS_ENV} key {version} must decode to 32 bytes"
            );
            assert!(
                versions.insert(version),
                "{ARCHIVE_KEYS_ENV} repeats key version {version}"
            );
            (version, key)
        })
        .collect()
}

fn render(keys: &[(u32, Vec<u8>)]) -> String {
    let entries = keys
        .iter()
        .map(|(version, key)| {
            let mut mask = vec![0u8; key.len()];
            getrandom::fill(&mut mask).expect("random mask");
            let masked: Vec<String> = key
                .iter()
                .zip(&mask)
                .map(|(k, m)| (k ^ m).to_string())
                .collect();
            let mask: Vec<String> = mask.iter().map(u8::to_string).collect();
            format!(
                "    ArchiveKeyMaterial {{ version: {version}, masked: &[{}], mask: &[{}] }},\n",
                masked.join(", "),
                mask.join(", ")
            )
        })
        .collect::<String>();
    format!(
        "// Generated by build.rs. Contains key material: never commit.\npub(crate) static ARCHIVE_KEYS: &[ArchiveKeyMaterial] = &[\n{entries}];\n"
    )
}

fn main() {
    println!("cargo:rerun-if-env-changed={ARCHIVE_KEYS_ENV}");
    let keys = parse_archive_keys(&env::var(ARCHIVE_KEYS_ENV).unwrap_or_default());
    // Versions only, never key material: lets a build log prove the binary can decrypt archives.
    let versions: Vec<String> = keys
        .iter()
        .map(|(version, _)| version.to_string())
        .collect();
    println!(
        "cargo:warning=[bible-strong-archive] Offline-copy key versions: {}",
        if versions.is_empty() {
            "none".to_string()
        } else {
            versions.join(", ")
        }
    );
    let out = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR")).join("archive_keys.rs");
    fs::write(out, render(&keys)).expect("write archive key material");

    tauri_build::build()
}
